for i in range (5): #gera valores de 0 até 4
    print(i)

for i in range (1,5): #gera valores de 1 até 4
    print(i)

#range (2, 11, 2) -> começa em 2, vai até 10 e incrementa de 2 em 2
#range (4, 0, -1) -> começa em 4, vai até 1 e decrementa de 1 em 1

#for (each)
palavra = "profe"

